'use strict';
// ─────────────────────────────────────────────────────────────────────────────
//  THE CYBER PRACTICE HUB AND SPOKE: the Matrixify sheet.
//
//  Seven rows, and the split between them is the whole safety story:
//
//    5 CREATE   ap-cybersecurity-unit-N-practice, N = 1..5. All five confirmed
//               404 on the live storefront before this was written. A MERGE
//               against a live handle overwrites its body, and that near-miss
//               has already happened once on a cyber lab page.
//    2 EXTEND   ap-cybersecurity-practice and ap-cybersecurity-topics. Both are
//               live, so their rows are built FROM the live body through
//               lib/link-block.js, which refuses rather than rewrites: it
//               checks div balance, anchor count and byte growth against the
//               input and hands back the original on any doubt.
//
//  ── WHY THE EXTENSIONS ARE NOT REGENERATED ─────────────────────────────────
//  ap-cybersecurity-practice was generated by scripts/cyber-practice-hubs-csv.js
//  and carries an FRQ section and a labs section that re-render from /api/
//  practice on load. Regenerating it here would be a second opinion about a
//  page another generator owns, and the copy is always the one that rots. So
//  this adds a links block to what is there and touches nothing else.
//
//  ── STATIC HTML, NOT A SCRIPT ──────────────────────────────────────────────
//  The spoke cards are real HTML. A page whose content only appears after
//  JavaScript is a page a crawler reads as empty, and the whole point of the
//  practice layer is that it ranks for practice intent by spring.
//
//  House Matrixify rules: MERGE, QUOTE_ALL, utf-8-sig, past-dated Published At,
//  Body HTML never empty. One import at a time.
//
//  Run: node tools/ap-cyber-ced/generate-practice-sheet.js \
//         --bodies <dir> --handles <file> [--out <file.csv> | --dry-run]
// ─────────────────────────────────────────────────────────────────────────────

