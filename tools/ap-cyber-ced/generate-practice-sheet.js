function spokeBody(s) {
  const u = spec.umbrella();
  const id = `apcs-cyber-u${s.unit_no}-practice`;
  const groups = KIND_ORDER
    .filter((k) => s.assets[k] && s.assets[k].length)
    .map((k) => {
      const chips = s.assets[k]
        .map((h) => `<li><a href="/pages/${esc(h)}">${esc(labelFor(h))}</a></li>`)
        .join('');
      return `<div class="grp"><h3>${esc(KIND[k].label)}</h3>`
        + `<p class="why">${esc(KIND[k].blurb)}</p>`
        + `<ul class="chips">${chips}</ul></div>`;
    })
    .join('\n');

  //  The onward row is where "connected to the course" becomes literal: the
  //  unit study page, the course guide, the practice hub and the sibling unit.
  const course = s.course_lesson_handles
    .map((h) => `<li><a class="alt" href="/pages/${esc(h)}">${esc(labelFor(h))}</a></li>`)
    .join('');

  const total = s.asset_count;
  return `${CSS(id)}
<div id="${id}">
<p class="crumb"><a href="/pages/${esc(u.topics_hub)}">AP Cybersecurity</a> &rsaquo; <a href="/pages/${esc(u.handle)}">Practice</a> &rsaquo; Unit ${s.unit_no}</p>
<h1>AP Cybersecurity Unit ${s.unit_no} Practice: ${esc(s.unit_name)}</h1>
<p class="lede">Every piece of practice for Unit ${s.unit_no}, in one place: ${total} quizzes, exercises, labs and exams, in the order you should meet them. Unit ${s.unit_no} covers CED topics ${esc(s.topics.join(', '))}.</p>
<p>Work down the page. The quizzes and exercises are short enough to do between lessons, the labs take a class period, and the unit exam is worth saving until the rest is done.</p>
${groups}
<h2>Keep going</h2>
<ul class="onward">
<li><a href="/pages/${esc(s.unit_study_page)}">Study Unit ${s.unit_no}</a></li>
<li><a href="/pages/${esc(u.handle)}">All AP Cybersecurity practice</a></li>
<li><a class="alt" href="/pages/${esc(u.course_guide)}">Full course guide</a></li>
${course}
</ul>
</div>`;
}

function seoDescription(s) {
  return `Practice AP Cybersecurity Unit ${s.unit_no}: ${s.asset_count} quizzes, exercises, terminal labs`
    + ` and the unit exam, covering CED topics ${s.topics.join(', ')}. Free and auto-scored.`;
}

// ─────────────────────────────────────────────────────────────────────────────
//  The two live pages. Built from the stored body through lib/link-block.js.
//  A missing body file is a REFUSAL, never an empty cell: an empty Body HTML in
//  a MERGE import erases the live page.
// ─────────────────────────────────────────────────────────────────────────────
function extendRow(handle, links, bodies, live, opts = {}) {
  const file = path.join(bodies, `${handle}.html`);
  if (!fs.existsSync(file)) {
    throw new Error(`no stored body for ${handle} at ${file}. Fetch it before generating:`
      + ' an empty Body HTML cell would erase the live page.');
  }
  let base = fs.readFileSync(file, 'utf8');
  if (!base.trim()) throw new Error(`stored body for ${handle} is empty`);

  //  Dead-anchor repair, before the link block. Each repair must actually match
  //  something: a repair that changes nothing means the page moved under us and
  //  the rest of this row can no longer be trusted, so it throws rather than
  //  shipping a body built on a stale assumption.
  let repaired = 0;
  for (const rp of (opts.repairs || [])) {
    const rx = new RegExp(`/pages/${rp.from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![a-z0-9-])`, 'g');
    const hits = (base.match(rx) || []).length;
    if (!hits) throw new Error(`repair for ${handle} found no /pages/${rp.from} to fix`);
    base = base.replace(rx, `/pages/${rp.to}`);
    repaired += hits;
  }

  const res = linkBlock.build(base, links, live, {
    selfHandle: handle,
    max: linkBlock.MAX_LINKS_HUB,
    heading: opts.heading || 'Related Resources',
  });
  if (!res.changed) throw new Error(`${handle} already carries every link, so the sheet would be a no-op`);
  //  `base` is the REPAIRED body, which is what P5 must compare against:
  //  the repair is part of what this package authored on that page.
  return { body: res.body, base, added: res.added, dropped: res.dropped, repaired };
}

//  ── WHY THIS EMITS TWO SHEETS AND NOT ONE ─────────────────────────────────
//  scripts/matrixify-preflight.js refused the single-sheet version, and it was
//  right. A BLANK cell in a Matrixify import does not mean "leave this column
//  alone", it means "set this column to empty". The five new pages need Title,
//  Published, Published At and both SEO columns; the two live hubs need only a
//  new Body HTML. Putting them in one file left those five columns blank on the
//  hub rows, which on import would have erased the title of
//  ap-cybersecurity-topics and UNPUBLISHED it.
//
//  So the split is not tidiness. Every column in a sheet must be a column every
//  row in it is changing, which is the rule the preflight states and the reason
//  it counts blanks per column.
const CREATE_HEADER = HEADER;
const EXTEND_HEADER = ['Handle', 'Command', 'Body HTML'];

function sheetOf(rows, specs, header, live, newHandles) {
  const { csv, drift } = roundTrip(rows, header);
  const report = validate(parseCsv(csv), { specs, liveHandles: live, newHandles });
  return { rows, specs, header, csv, drift, report };
}

function generate(opts = {}) {
  const bodies = opts.bodies;
  const live = opts.liveHandles;
  const u = spec.umbrella();
  //  The five spokes are created by THIS package, so they are not live yet and
  //  lib/link-block.js is right to drop a handle it cannot show exists. They
  //  land in the same import batch as the two hub updates, so for the purpose
  //  of rendering those two blocks they resolve. Nothing else joins the set: a
  //  typo'd handle is still dropped, which is the protection that matters.
  const newHandles = spec.spokes().map((s) => s.handle);
  const resolvable = new Set([...live, ...newHandles]);
  const notes = [];

  //  SHEET 1: the five new spokes, every column populated.
  const createRows = [];
  const createSpecs = [];
  for (const s of spec.spokes()) {
    createRows.push({
      Handle: s.handle,
      Command: 'MERGE',
      Title: s.title,
      'Body HTML': spokeBody(s),
      Published: 'TRUE',
      'Published At': PUBLISHED_AT,
      //  The title already opens with the course name, so the usual
      //  " | AP Cybersecurity" suffix would say it twice.
      'SEO Title': `${s.title} | Free Practice`,
      'SEO Description': seoDescription(s),
    });
    createSpecs.push({ created: true, unit_no: s.unit_no, body_update: true });
  }

  //  SHEET 2: the two live hubs, Body HTML only.
  const extendRows = [];
  const extendSpecs = [];

  const hubLinks = spec.spokes().map((s) => ({
    handle: s.handle,
    label: `Unit ${s.unit_no} practice: ${s.unit_name}`,
  }));
  const hub = extendRow(u.handle, hubLinks, bodies, resolvable, { heading: 'Practice by unit' });
  extendRows.push({ Handle: u.handle, Command: 'MERGE', 'Body HTML': hub.body });
  extendSpecs.push({ created: false, body_update: true, base_body: hub.base });
  notes.push(`${u.handle}: added ${hub.added.length} links`);

  //  One edge, and it is the one that was missing entirely: the concept hub
  //  linked no practice page at all.
  const topics = extendRow(u.topics_hub, [
    { handle: u.handle, label: 'AP Cybersecurity practice: quizzes, labs and exams' },
  ], bodies, resolvable, { heading: 'Practice' });
  extendRows.push({ Handle: u.topics_hub, Command: 'MERGE', 'Body HTML': topics.body });
  extendSpecs.push({ created: false, body_update: true, base_body: topics.base });
  notes.push(`${u.topics_hub}: added ${topics.added.length} links`);

  //  The edge and coverage rules read the whole package, so they are validated
  //  against BOTH sheets together. Validating each file alone would report
  //  every cross-sheet edge as missing.
  //  SHEET 3: the reverse edge. Seven live pages gain a link INTO the practice
  //  layer. Body HTML only, same as sheet 2, and built from each page's own
  //  live body through lib/link-block.js so nothing else on them moves.
  const reverseRows = [];
  const reverseSpecs = [];
  const guideRows = [];
  const guideSpecs = [];
  for (const e of spec.reverseSources()) {
    //  A page flagged needs_repair has dead anchors of its own. They are
    //  repaired BEFORE the link block goes on, because R6 reads the finished
    //  row and a MERGE republishes every link on the page, dead ones included.
    const repairs = e.needs_repair ? spec.courseGuideRepairs() : [];
    const r = extendRow(e.from, [{ handle: e.to, label: e.label }], bodies, resolvable,
      { heading: 'Practice', repairs });
    const row = { Handle: e.from, Command: 'MERGE', 'Body HTML': r.body };
    const sp = { created: false, body_update: true, base_body: r.base };
    if (e.needs_repair) {
      guideRows.push(row); guideSpecs.push(sp);
      notes.push(`${e.from}: added ${r.added.length} link, repaired ${r.repaired} dead anchor(s)`);
    } else {
      reverseRows.push(row); reverseSpecs.push(sp);
      notes.push(`${e.from}: added ${r.added.length} link to ${e.to}`);
    }
  }

  const allRows = [...createRows, ...extendRows, ...reverseRows, ...guideRows];
  const allSpecs = [...createSpecs, ...extendSpecs, ...reverseSpecs, ...guideSpecs];
  const whole = sheetOf(allRows, allSpecs, CREATE_HEADER, live, newHandles);

  return {
    create: sheetOf(createRows, createSpecs, CREATE_HEADER, live, newHandles),
    extend: sheetOf(extendRows, extendSpecs, EXTEND_HEADER, live, newHandles),
    reverse: sheetOf(reverseRows, reverseSpecs, EXTEND_HEADER, live, newHandles),
    guide: sheetOf(guideRows, guideSpecs, EXTEND_HEADER, live, newHandles),
    whole,
    rows: allRows,
    specs: allSpecs,
    drift: whole.drift,
    report: whole.report,
    notes,
    newHandles,
  };
}

function main() {
  const argv = process.argv.slice(2);
  const arg = (n) => { const i = argv.indexOf(n); return i === -1 ? null : argv[i + 1]; };
  const bodies = arg('--bodies');
  const handlesFile = arg('--handles');
  const outDir = arg('--out-dir');
  if (!bodies || !handlesFile) {
    console.error('usage: generate-practice-sheet.js --bodies <dir> --handles <file> [--out-dir <dir>]');
    process.exit(2);
  }
  const live = new Set(fs.readFileSync(handlesFile, 'utf8').split('\n').map((s) => s.trim()).filter(Boolean));
  const res = generate({ bodies, liveHandles: live });

  for (const n of res.notes) console.log(`  ${n}`);

  //  Parse-back is checked on each file that will actually be imported, and on
  //  the package as a whole. Generation is not evidence that generation worked.
  const drift = [...res.create.drift, ...res.extend.drift, ...res.reverse.drift,
    ...res.guide.drift, ...res.whole.drift];
  if (drift.length) {
    console.error('\nPARSE-BACK DRIFT. A sheet does not read back as what was written:');
    for (const d of drift) console.error(`  ${d}`);
    process.exit(1);
  }
  console.log(`\nparse-back: clean (${res.create.rows.length} new + ${res.extend.rows.length} extended`
    + ` + ${res.reverse.rows.length} reverse-linked)`);

  if (res.report.fail.length) {
    console.error(`\nVALIDATOR REFUSED (${res.report.fail.length}):`);
    for (const f of res.report.fail.slice(0, 40)) console.error(`  ${f}`);
    process.exit(1);
  }
  console.log('validator: clean on all 11 rules');

  if (outDir) {
    //  The file NAME carries the sheet type: a CSV has no tab name, so
    //  Matrixify reads the type off the filename and rejects the whole file in
    //  one second if it cannot find one.
    const files = [
      ['cyber-practice-new-pages.csv', res.create],
      ['cyber-practice-hub-links-pages.csv', res.extend],
      ['cyber-practice-reverse-links-pages.csv', res.reverse],
      ['cyber-course-guide-repair-pages.csv', res.guide],
    ];
    for (const [name, sheet] of files) {
      const f = path.join(outDir, name);
      fs.writeFileSync(f, sheet.csv);
      console.log(`wrote ${f} (${Buffer.byteLength(sheet.csv)} bytes, ${sheet.rows.length} rows)`);
    }
    console.log('\nIMPORT ORDER: the new pages FIRST, then either link sheet.');
    console.log('Both link sheets point at the five new handles, so importing one of them');
    console.log('first would publish pages linking 404s.');
  } else {
    console.log('(no --out-dir, nothing written)');
  }
}

if (require.main === module) main();
module.exports = { generate, spokeBody, labelFor, seoDescription, extendRow, KIND, KIND_ORDER };
