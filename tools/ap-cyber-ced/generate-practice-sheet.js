//  A handle becomes a readable card label. Derived from the handle rather than
//  fetched, because a title is a claim about a live page and this is a link
//  label, not a claim. Kept boring on purpose.
function labelFor(handle) {
  const m = /^ap-cyber-unit-(\d)-lesson-(\d+)-(.*)$/.exec(handle);
  if (m) {
    const [, , lesson, tail] = m;
    if (tail === 'quiz') return `Lesson ${lesson} quiz`;
    const ex = /^exercise-(\d+)$/.exec(tail);
    if (ex) return `Lesson ${lesson} exercise ${ex[1]}`;
    if (tail === 'lab') return `Lesson ${lesson} lab`;
    if (tail === 'terminal-lab') return `Lesson ${lesson} terminal lab`;
    return `Lesson ${lesson} ${tail.replace(/-/g, ' ')}`;
  }
  const c = /^ap-cyber-unit-(\d)-case-file-\d+$/.exec(handle);
  if (c) return `Unit ${c[1]} case file`;
  const named = /^ap-cyber-unit-(\d)-lab-(.+)$/.exec(handle);
  if (named) return `Lab: ${named[2].replace(/-/g, ' ')}`;
  const rest = /^ap-cyber-unit-(\d)-(.+)$/.exec(handle);
  if (rest) {
    const t = rest[2].replace(/-/g, ' ');
    return `Unit ${rest[1]} ${t}`;
  }
  //  Units 1 and 2 keep slug handles for their lesson pages, so the label comes
  //  from the slug. Sentence case, because "unit 1 social engineering" in a
  //  link reads as a bug rather than as a lesson. The CED title is deliberately
  //  NOT used here: carrying it would be the cannibalisation P1 exists to stop.
  const slug = /^ap-cybersecurity-unit-(\d)-(.+)$/.exec(handle);
  if (slug) return `Unit ${slug[1]}: ${sentenceCase(slug[2].replace(/-/g, ' '))}`;
  return sentenceCase(handle.replace(/^ap-cybersecurity-/, '').replace(/-/g, ' '));
}

//  Initialisms the site writes in capitals. Everything else takes a leading
//  capital and is otherwise left as authored.
const CAPS = new Set(['ai', 'vpn', 'mfa', 'dns', 'ddos', 'sql', 'xss', 'ids', 'ips', 'siem', 'mac', 'iot']);
function sentenceCase(text) {
  const words = String(text).split(' ').map((w) => (CAPS.has(w.toLowerCase()) ? w.toUpperCase() : w));
  if (!words.length) return text;
  words[0] = words[0].charAt(0).toUpperCase() + words[0].slice(1);
  return words.join(' ');
}

