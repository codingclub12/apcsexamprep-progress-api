//  WHY THESE BUGS
//  Unit 3 has a specific failure mode that Units 1 and 2 do not: the code
//  compiles, the class looks textbook-correct, and the fields are silently zero
//  or the count is silently one. A student who has only ever debugged by
//  reading an error message is helpless here, because there is no message. The
//  planted bugs are the four that produce that exact experience:
//    - a local declaration shadowing the field it was meant to set (3.3, 3.8)
//    - a constructor with a return type, which is a method, so the object is
//      built by the default constructor instead (3.4)
//    - an instance variable that should have been static (3.7)
//    - a returned reference that lets a caller reach inside the object (3.6)
