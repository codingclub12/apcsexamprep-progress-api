// ─────────────────────────────────────────────────────────────────────────────
//  CSA CODE TEST BANK — hidden test cases for server-side code grading.
//
//  Each graded code item (a lesson's exercise-1 / exercise-2 / frq) carries a set
//  of test cases: an stdin, the expected stdout, and a hidden flag. The grader
//  (POST /api/student/code-grade) runs the student's source against every case
//  through the Judge0 proxy and scores cases-passed / total. Cases NEVER reach the
//  client, so the page source cannot double as an answer key.
//
//  Integrity rule enforced by the loader: at least three cases per item and at
//  least one hidden. The visible expected output can leak into the page (it is the
//  worked example), but a hardcoded System.out.println of it fails the hidden
//  cases, which use different inputs. That is the same fix applied to the quizzes:
//  the correct answers live server-side, not in the page.
//
//  These are the CSA Unit 1 pilot exercises. Each expected_stdout was GENERATED by
//  running a known-correct reference solution through real javac/java, so the
//  cases are internally consistent (verified: the reference solution passes 4/4,
//  a hardcoded-visible-output cheat passes only 1/4, and a wrong-logic solution
//  passes 0/4). Language is not fixed per item: any allow-listed language whose
//  stdout matches passes, so the same case set grades a Java, Python, or JS answer.
//
//  IMPORTANT: each item's I/O CONTRACT below must match what the lesson page asks
//  the student to write. If a live page's prompt differs, update the cases here and
//  re-run `node scripts/seed-code-tests.js --update`. Author content only; zero
//  student PII. No student source is ever stored. No em-dashes.
//
//  I/O contracts (Unit 1: Using Objects and Methods):
//    1.1 exercise-1: read one line (a word); print its length, then the word
//        uppercased. Uses String.length() and String.toUpperCase().
//    1.2 exercise-1: read two integers, each on its own line; print a+b, a-b, a*b,
//        each on its own line. Arithmetic expressions and output.
//    1.3 exercise-1: read two integers, each on its own line; print the larger
//        then the smaller. Uses Math.max() and Math.min().
// ─────────────────────────────────────────────────────────────────────────────

