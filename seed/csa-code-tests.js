// ─────────────────────────────────────────────────────────────────────────────
//  CSA CODE TEST BANK — hidden test cases for server-side code grading.
//
//  Each graded code item (a lesson's exercise-1 / exercise-2 / frq) carries a set
//  of test cases: an stdin, the expected stdout, and a hidden flag. The grader
//  (POST /api/student/code-grade) runs the student's source against every case
//  through the Judge0 proxy and scores cases-passed / total. Cases NEVER reach the
//  client, so the page source cannot double as an answer key.
//
//  Integrity rule enforced by the loader: at least three cases per item and at
//  least one hidden. The hardcoding defense REQUIRES the problem to READ INPUT:
//  hidden cases feed inputs the page never shows, so a hardcoded
//  System.out.println of the visible expected output fails them. A no-input,
//  fixed-output problem cannot be made hardcode-proof by output comparison alone
//  (client OR server), so every graded item here reads stdin.
//
//  Alignment note (2025-2026 four-unit CED): Scanner input is introduced in
//  lesson 1.4 (Assignment Statements and Input), so input-driven code grading fits
//  lesson 1.4 and later. Lessons 1.1-1.3 come before input is taught; their code
//  editors stay on the existing client path until they can be posed with input.
//  Each item's topic is placed on its REAL lesson: input on 1.4, the Math class on
//  1.11, String manipulation on 1.15.
//
//  Each expected_stdout was GENERATED by running a known-correct reference solution
//  through real javac/java, then checked so the reference passes 4/4, a hardcoded
//  cheat passes at most 1/4, and a wrong-logic solution fails. See the I/O
//  contracts below; the lesson page must feed the same stdin and pose the same
//  task. The reporter posts item = the activity_type ('exercise-1'), which is the
//  denominator key in course_denominators (exercise-1 = 10 points).
//
//  Loaded manually by scripts/seed-code-tests.js (never on boot), same posture as
//  the quiz bank. Author content only; zero student PII. No student source is ever
//  stored. No em-dashes.
//
//  I/O contracts:
//    1.4  exercise-1 (Assignment Statements and Input): read two integers, each on
//         its own line; print their sum on line 1, their product on line 2.
//    1.11 exercise-1 (Math Class): read two integers, each on its own line; print
//         the larger (Math.max) on line 1, the absolute difference (Math.abs) on
//         line 2.
//    1.15 exercise-1 (String Manipulation): read one line (a word of length >= 3);
//         print its length on line 1, its first three characters (substring(0,3))
//         on line 2.
// ─────────────────────────────────────────────────────────────────────────────

