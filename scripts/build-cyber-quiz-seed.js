'use strict';
// ─────────────────────────────────────────────────────────────────────────────
//  WRITE seed/cyber-units-2-5-web-quizzes.js FROM THE LIVE PAGES.
//
//  Companion to scripts/extract-cyber-quizzes.js. The extractor parses; this
//  writes the file, so the seed is derived rather than typed and can be
//  re-derived with --check to prove it still matches the pages.
//
//  ── WHY THESE QUESTIONS ARE SAFE TO PUBLISH SERVER-SIDE ────────────────────
//  seed/cyber-unit-1-web-quizzes.js states the rule this repo learned the
//  expensive way: never seed a TEACHER BUNDLE question into an online bank,
//  because a bundle instrument's security is that it is not published.
//
//  Every question here is ALREADY PUBLISHED. It is parsed out of a live page
//  that serves it to anyone, alongside its answer key. Moving it server-side
//  therefore cannot expose anything: it strictly REDUCES exposure, because the
//  key stops being in the page. That is the opposite of the 2026-08-26 incident,
//  which took unpublished bundle items and put them on a public page.
//
//  The bundle instruments are 9 to 24 items. Every one of these pages carries
//  five or six, measured, so none of them is a bundle instrument wearing a web
//  quiz's clothes. That is a signal and not a proof: the .docx files are not in
//  this repo, so no diff against them is possible here, and a question that
//  turns out to be shared with a bundle should be re-authored rather than left.
//
//  ── PUNCTUATION IS CARRIED VERBATIM, DELIBERATELY ──────────────────────────
//  These options and stems contain em-dashes, curly quotes and arrows, because
//  the pages they came from do. The repo's no-em-dash rule governs text we
//  AUTHOR, and rewriting 116 of them here would change what a student reads
//  while claiming to be a migration, which is exactly the thing that cannot then
//  be verified as a migration. The punctuation pass is a separate change.
//
//  Run: node scripts/build-cyber-quiz-seed.js <bodies-dir> [--check]
// ─────────────────────────────────────────────────────────────────────────────
const fs = require('fs');
const path = require('path');
const { extract } = require('./extract-cyber-quizzes');

const OUT = path.join(__dirname, '..', 'seed', 'cyber-units-2-5-web-quizzes.js');
const j = (v) => JSON.stringify(v);

function render(quizzes) {
  const lines = [];
  lines.push("'use strict';");
  lines.push('// ---------------------------------------------------------------------------');
  lines.push('//  AP CYBERSECURITY UNITS 2 TO 5 - WEB QUIZZES, LIFTED OFF THE PAGES.');
  lines.push('//');
  lines.push('//  GENERATED by scripts/build-cyber-quiz-seed.js from the live page bodies.');
  lines.push('//  Do not hand edit: run that script with --check to prove this file still');
  lines.push('//  matches what the pages serve.');
  lines.push('//');
  lines.push('//  Every question here was ALREADY PUBLISHED on its page, with its answer key');
  lines.push('//  beside it. Serving it from quiz_bank instead removes the key from the page');
  lines.push('//  and lets a teacher lock actually withhold the quiz. It publishes nothing');
  lines.push('//  that was not already public, which is the opposite of the 2026-08-26');
  lines.push('//  incident that seed/cyber-unit-1-web-quizzes.js was written to prevent.');
  lines.push('//');
  lines.push('//  Options are stored WITHOUT their letters and in authored order, because');
  lines.push('//  routes/quiz.js reshuffles them per render. An explanation that named an');
  lines.push('//  option letter was dropped for the same reason rather than shipped false.');
  lines.push('//');
  lines.push('//  Punctuation is verbatim from the pages, including em-dashes. See the header');
  lines.push('//  of the generator for why a migration does not also rewrite copy.');
  lines.push('//');
  lines.push('//  Zero PII: author content only.');
  lines.push('// ---------------------------------------------------------------------------');
  lines.push('');
  lines.push('module.exports = [');
  for (const q of quizzes) {
    lines.push('  {');
    lines.push(`    location: ${j(q.location)},`);
    lines.push(`    // ${q._handle}, parsed from the ${q._generation} generation`);
    lines.push('    questions: [');
    for (const x of q.questions) {
      lines.push('      {');
      lines.push(`        qid: ${j(x.qid)},`);
      lines.push(`        points: ${x.points},`);
      lines.push(`        prompt: ${j(x.prompt)},`);
      lines.push('        options: [');
      for (const o of x.options) lines.push(`          ${j(o)},`);
      lines.push('        ],');
      lines.push(`        correct_index: ${x.correct_index},`);
      if (x.explanation) lines.push(`        explanation: ${j(x.explanation)},`);
      if (x._explanation_names_letters) {
        lines.push('        // explanation dropped: it named an option letter, which is false');
        lines.push('        // once routes/quiz.js reshuffles the options.');
      }
      lines.push('      },');
    }
    lines.push('    ],');
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

if (require.main === module) {
  const dir = process.argv[2];
  if (!dir) { console.error('usage: node scripts/build-cyber-quiz-seed.js <bodies-dir> [--check]'); process.exit(2); }
  const quizzes = extract(dir);
  if (!quizzes.length) { console.error('no quizzes parsed'); process.exit(1); }
  const text = render(quizzes);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('seed/cyber-units-2-5-web-quizzes.js is stale or hand edited.'); process.exit(1); }
    console.log('seed matches the live pages');
    process.exit(0);
  }
  fs.writeFileSync(OUT, text);
  const n = quizzes.reduce((a, q) => a + q.questions.length, 0);
  console.log(`wrote ${OUT}`);
  console.log(`  ${quizzes.length} quizzes, ${n} questions`);
}
