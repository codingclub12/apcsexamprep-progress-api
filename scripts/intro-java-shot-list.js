'use strict';
// ─────────────────────────────────────────────────────────────────────────────
//  GENERATE THE SCREENSHOT SHOT LIST.
//
//  The content bank references 158 screenshots. This turns them into a document
//  somebody can actually work from at a keyboard with Greenfoot open: what to
//  capture, in what order, what code is on screen at that moment, and the exact
//  filename to save it as.
//
//  WHY GENERATED AND NOT HAND-WRITTEN
//  The bank is the source of truth for what shots exist. A hand-maintained list
//  goes stale the first time a lesson gains a step, and then somebody shoots 4
//  images for a lesson that now needs 5 and nobody notices until a page is live
//  with a gap in the middle of a walkthrough.
//
//  Regenerate any time the content changes:
//      node scripts/intro-java-shot-list.js
//
//  Writes docs/intro-java-shot-list.md and docs/intro-java-shot-list.csv. The
//  CSV is for tracking progress across a few sessions; the markdown is for
//  reading while you work.
//
//  Zero PII. No em-dashes, per repo convention.
// ─────────────────────────────────────────────────────────────────────────────
const fs = require('fs');
const path = require('path');

const { BANKS } = require('../seed/intro-java-banks');
const { hasShot } = require('../seed/intro-java-shots');

const ROOT = path.join(__dirname, '..');

// The theme flattens paths, so intro-java/1.1/step-1.png uploads as
// intro-java-1.1-step-1.png. Printing both is what stops the upload step going
// wrong, since the two names are close enough to look interchangeable.
const uploadName = (src) => src.split('/').join('-');

function collect() {
  const rows = [];
  for (const bank of BANKS) {
    for (const lesson of bank.lessons) {
      lesson.steps.forEach((step, i) => {
        if (!step.shot) return;
        rows.push({
          unit: bank.unit,
          unitLabel: bank.label,
          lesson: lesson.lesson,
          lessonTitle: lesson.title,
          step: i + 1,
          src: step.shot.src,
          upload: uploadName(step.shot.src),
          capture: step.shot.alt,
          code: step.code || '',
          done: hasShot(step.shot.src),
        });
      });
    }
  }
  return rows;
}

function markdown(rows) {
  const done = rows.filter((r) => r.done).length;
  const out = [];

  out.push('# Intro to Java: screenshot shot list');
  out.push('');
  out.push('GENERATED by `node scripts/intro-java-shot-list.js`. Do not hand-edit;');
  out.push('regenerate after any content change.');
  out.push('');
  out.push(`**${done} of ${rows.length} taken.**`);
  out.push('');
  out.push('## Before you start');
  out.push('');
  out.push('Read this once. It is the difference between a set that looks professional and');
  out.push('one that looks like it was assembled over six months, which it will be.');
  out.push('');
  out.push('- **Build each scenario for real and shoot as you go.** The lessons promise that');
  out.push('  every step leaves a scenario that compiles and runs. Shooting in order is how');
  out.push('  you find out whether that is actually true, and it is the one part of this');
  out.push('  that cannot be faked afterwards from a finished project.');
  out.push('- **Fix the window size before the first shot of a unit and do not touch it.**');
  out.push('  A set shot at three sizes reads as sloppy even when each individual shot is');
  out.push('  fine. 1440 by 900 is a good default.');
  out.push('- **Same scenario, same actors, same zoom** across a whole unit.');
  out.push('- **Crop to what the step is about.** If the step is about the class diagram,');
  out.push('  the shot is the class diagram, not the whole desktop.');
  out.push('- **No student names, no file paths with your username, no email in the title');
  out.push('  bar.** These pages are used by minors in schools.');
  out.push('- **Note the Greenfoot version** you shot against at the top of your notes. A');
  out.push('  version bump is a reshoot of the affected steps, and you will not remember.');
  out.push('');
  out.push('## The pages work without these');
  out.push('');
  out.push('Nothing is blocked. Until a shot is listed in `seed/intro-java-shots.js`, the');
  out.push('page prints its description as an instruction instead:');
  out.push('');
  out.push('> On your screen: the class diagram panel, showing World with a subclass beneath');
  out.push('> it and Actor with several subclasses beneath it.');
  out.push('');
  out.push('So you can ship the course today and add shots one at a time, in any order,');
  out.push('and every one you add upgrades a page with no other change.');
  out.push('');
  out.push('## How to add one');
  out.push('');
  out.push('1. Take the shot.');
  out.push('2. Upload it to the theme under the **Upload as** name below (the theme');
  out.push('   flattens the folders, so the slashes become dashes).');
  out.push('3. Add the **Path** to the `AVAILABLE` list in `seed/intro-java-shots.js`.');
  out.push('4. `npm run smoke:introjava`. A path that does not match a real shot fails,');
  out.push('   so a typo cannot silently show nothing.');
  out.push('');

  let currentUnit = null;
  let currentLesson = null;
  for (const r of rows) {
    if (r.unit !== currentUnit) {
      currentUnit = r.unit;
      currentLesson = null;
      const unitRows = rows.filter((x) => x.unit === r.unit);
      const unitDone = unitRows.filter((x) => x.done).length;
      out.push('');
      out.push(`## ${r.unitLabel}`);
      out.push('');
      out.push(`${unitDone} of ${unitRows.length} taken.`);
    }
    if (r.lesson !== currentLesson) {
      currentLesson = r.lesson;
      out.push('');
      out.push(`### ${r.lesson} ${r.lessonTitle}`);
      out.push('');
    }
    out.push(`**Step ${r.step}** ${r.done ? '(taken)' : ''}`);
    out.push('');
    out.push(`- **Capture:** ${r.capture}`);
    out.push(`- **Path:** \`${r.src}\``);
    out.push(`- **Upload as:** \`${r.upload}\``);
    if (r.code) {
      out.push('- **Code on screen at this step:**');
      out.push('');
      out.push('  ```java');
      for (const line of r.code.split('\n')) out.push(`  ${line}`);
      out.push('  ```');
    }
    out.push('');
  }

  return out.join('\n');
}

function csv(rows) {
  const esc = (v) => `"${String(v).split('"').join('""')}"`;
  const lines = ['taken,unit,lesson,step,path,upload_as,capture'];
  for (const r of rows) {
    lines.push([
      r.done ? 'yes' : 'no', r.unit, r.lesson, r.step, r.src, r.upload, r.capture,
    ].map(esc).join(','));
  }
  // utf-8 BOM so Excel does not mangle it, same as the Matrixify sheets.
  return '﻿' + lines.join('\n') + '\n';
}

function main() {
  const rows = collect();
  const mdPath = path.join(ROOT, 'docs', 'intro-java-shot-list.md');
  const csvPath = path.join(ROOT, 'docs', 'intro-java-shot-list.csv');
  fs.writeFileSync(mdPath, markdown(rows));
  fs.writeFileSync(csvPath, csv(rows));

  const done = rows.filter((r) => r.done).length;
  const byUnit = {};
  for (const r of rows) byUnit[r.unit] = (byUnit[r.unit] || 0) + 1;

  console.log(`shot list: ${rows.length} screenshots across ${BANKS.length} units`);
  for (const [u, n] of Object.entries(byUnit)) console.log(`  ${u}: ${n}`);
  console.log(`taken so far: ${done}`);
  console.log(`wrote ${path.relative(ROOT, mdPath)}`);
  console.log(`wrote ${path.relative(ROOT, csvPath)}`);
}

if (require.main === module) main();

module.exports = { collect, markdown, csv, uploadName };
