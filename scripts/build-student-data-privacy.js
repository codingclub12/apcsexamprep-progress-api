function render(d) {
  const ads = d.student_pages_ad_free ? d.ads_clean : d.ads_current;
  const out = [];
  out.push(`<!-- Generated by scripts/build-student-data-privacy.js from content/student-data-privacy.json. Do not hand edit: regenerate. -->`);
  out.push(`<div id="${WRAPPER_ID}">`);
  out.push(STYLE);
  out.push(`<p class="sdp-updated">Last checked against the running system on ${esc(d.updated)}.</p>`);

  d.intro.forEach((p) => out.push(para(p)));

  out.push(h2(d.account_model.heading));
  d.account_model.paragraphs.forEach((p) => out.push(para(p)));

  out.push(h2(d.collected.heading));
  out.push(table(['What', 'Detail', 'Where it comes from'], d.collected.rows));

  out.push(h2(d.not_collected.heading));
  out.push(list(d.not_collected.items));

  out.push(h2(d.subprocessors.heading));
  out.push(para(d.subprocessors.lead));
  out.push(table(['Service', 'What it does', 'What it can see'], d.subprocessors.rows));

  out.push(h2(ads.heading));
  ads.paragraphs.forEach((p) => out.push(para(p)));

  out.push(h2(d.retention.heading));
  d.retention.paragraphs.forEach((p) => out.push(para(p)));

  out.push(h2(d.rights.heading));
  d.rights.paragraphs.forEach((p) => out.push(para(p)));

  out.push(h2(d.contact.heading));
  d.contact.paragraphs.forEach((p) => out.push(para(p)));

  out.push(`<p class="sdp-note">${esc(d.closing_note)}</p>`);
  out.push(`</div>`);
  return out.join('\n');
}

function sheet(d) {
  const header = ['Handle', 'Command', 'Title', 'Body HTML', 'Published', 'Published At'];
  const row = [d.handle, 'MERGE', d.title, render(d), 'TRUE', ''];
  return '﻿' + header.map(cell).join(',') + '\n' + row.map(cell).join(',') + '\n';
}

function main() {
  const d = JSON.parse(fs.readFileSync(DATA, 'utf8'));
  const csv = sheet(d);
  const check = process.argv.includes('--check');

  if (check) {
    if (!fs.existsSync(OUT)) {
      console.error('FAIL: ' + path.relative(ROOT, OUT) + ' does not exist. Run without --check.');
      process.exit(1);
    }
    const have = fs.readFileSync(OUT, 'utf8');
    if (have !== csv) {
      console.error('FAIL: the committed sheet is not what the canonical data renders.');
      console.error('      Regenerate: node scripts/build-student-data-privacy.js');
      process.exit(1);
    }
    console.log('OK: sheet matches content/student-data-privacy.json');
    return;
  }

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, csv, 'utf8');
  const body = render(d);
  console.log('wrote ' + path.relative(ROOT, OUT));
  console.log('  handle          ' + d.handle);
  console.log('  advertising     ' + (d.student_pages_ad_free ? 'ads_clean' : 'ads_current')
    + ' (student_pages_ad_free=' + d.student_pages_ad_free + ')');
  console.log('  body bytes      ' + Buffer.byteLength(body, 'utf8'));
  console.log('  sheet bytes     ' + Buffer.byteLength(csv, 'utf8'));
}

if (require.main === module) main();
module.exports = { render, sheet, WRAPPER_ID, DATA, OUT };
