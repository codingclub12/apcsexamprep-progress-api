'use strict';
// ─────────────────────────────────────────────────────────────────────────────
//  BUILD THE STUDENT DATA PRIVACY PAGE SHEET
//
//  content/student-data-privacy.json is the canonical data. This renders it into
//  one Matrixify page row. Nothing here authors copy: if a sentence needs to
//  change it changes in the JSON, so the page and the audit cannot drift apart.
//
//  THE FLAG. student_pages_ad_free picks which advertising section renders.
//  false is what is true on 2026-09-14 and says so plainly. Flip it only after
//  the theme actually stops loading Raptive and Clarity on student pages, then
//  regenerate and re-import. smoke/student-data-privacy.js refuses a body whose
//  advertising section disagrees with the flag, which is the whole point of
//  keeping it as data rather than as a paragraph somebody edits.
//
//    node scripts/build-student-data-privacy.js            write the sheet
//    node scripts/build-student-data-privacy.js --check    fail if it drifted
//
//  Zero PII. No em-dashes.
// ─────────────────────────────────────────────────────────────────────────────
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'content', 'student-data-privacy.json');
const OUT = path.join(ROOT, 'matrixify', 'student-data-privacy-pages.csv');

const WRAPPER_ID = 'apcs-sdp';

function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

//  Matrixify reads a normal RFC4180 cell. Double the quotes, keep the newlines.
function cell(s) {
  return '"' + String(s == null ? '' : s).replace(/"/g, '""') + '"';
}

function para(t) { return `<p class="sdp-p">${esc(t)}</p>`; }
function h2(t) { return `<h2 class="sdp-h2">${esc(t)}</h2>`; }

function table(headers, rows) {
  const head = headers.map((h) => `<th>${esc(h)}</th>`).join('');
  const body = rows.map((r) => '<tr>' + r.map((c) => `<td>${esc(c)}</td>`).join('') + '</tr>').join('');
  return `<div class="sdp-tablewrap"><table class="sdp-table">`
    + `<thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>`;
}

function list(items) {
  return `<ul class="sdp-list">${items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`;
}

